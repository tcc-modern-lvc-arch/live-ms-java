CREATE SCHEMA IF NOT EXISTS olhovivo;

CREATE TABLE IF NOT EXISTS olhovivo.bus_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_code INTEGER NOT NULL,
    line_sign TEXT,
    vehicle_prefix INTEGER NOT NULL,
    accessible BOOLEAN NOT NULL,
    position_timestamp TEXT,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    snapshot_reference TEXT,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE olhovivo.bus_positions ADD COLUMN IF NOT EXISTS line_sign TEXT;

CREATE INDEX IF NOT EXISTS idx_bus_positions_line_saved_at
    ON olhovivo.bus_positions (line_code, saved_at);

CREATE INDEX IF NOT EXISTS idx_bus_positions_vehicle_saved_at
    ON olhovivo.bus_positions (vehicle_prefix, saved_at);
