package io.github.raphonzius.lvc.live.infrastructure.output.persistence;

import io.github.raphonzius.lvc.live.domain.bus.BusVehicle;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class BusPositionJdbcAdapterTest {

    @Test
    void savesVehiclePositions() {
        var dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:buspositions-test;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                ""
        );
        var jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("""
                CREATE TABLE bus_positions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    line_code INTEGER NOT NULL,
                    vehicle_prefix INTEGER NOT NULL,
                    accessible BOOLEAN NOT NULL,
                    position_timestamp TEXT,
                    latitude DOUBLE PRECISION NOT NULL,
                    longitude DOUBLE PRECISION NOT NULL,
                    snapshot_reference TEXT,
                    saved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        new ResourceDatabasePopulator(new ClassPathResource("schema.sql")).execute(dataSource);
        var adapter = new BusPositionJdbcAdapter(jdbcTemplate);

        adapter.savePositions(1234, "178L-10", "10:30", List.of(
                new BusVehicle.VehicleData(5678, true, "2026-10-06T13:30:00Z", -23.5, -46.6)
        ));

        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM olhovivo.bus_positions WHERE line_code = ? AND line_sign = ? AND vehicle_prefix = ?",
                Integer.class,
                1234,
                "178L-10",
                5678
        )).isEqualTo(1);
    }
}
